"""Generates backend/crates/domain-iam/src/defaults.rs from PERMISSION_MATRIX.md (P9: the matrix is the default for the
system roles). Run from the repository root after the matrix changes:  python docs/domain/gen_default_grants.py
Cells: Y -> all, S -> scoped, Self -> self, A -> approve; '—', '?' and any cell with an open '?' part grant nothing.
Cfg(X) becomes setting_ref X. † (actor from a user story) is granted as written."""
import re

MATRIX = "docs/domain/PERMISSION_MATRIX.md"
OUT = "backend/crates/domain-iam/src/defaults.rs"
COLS = ["VA", "VS", "VR", "OA", "HR", "PO", "MGR", "SUP", "EMP", "AUD"]
ORG_ROLES = {"OA": "org_admin", "HR": "hr_manager", "PO": "payroll_officer", "MGR": "manager", "SUP": "supervisor", "EMP": "employee", "AUD": "auditor"}
VENDOR_ROLES = {"VA": "full_admin", "VS": "support", "VR": "read_only"}
# Platform rows acted on by organisation users (support access decided, ended and logged inside the organisation).
ORG_SIDE_PLT = {"PLT-14", "PLT-15", "PLT-18"}


def cell(c):
    c = c.strip().replace("†", "")
    if "?" in c:  # any open part (e.g. "S (location) / ? (selfie)") keeps the whole cell closed until the gap is decided
        return None, None
    ref = re.search(r"Cfg\(([^)]*)\)", c)
    head = re.sub(r"Cfg\([^)]*\)", "", c).strip().split()
    kind = {"Y": "all", "S": "scoped", "Self": "self", "A": "approve"}.get(head[0] if head else "")
    return kind, (ref.group(1).strip() if ref else None)


rows, section = [], None
for line in open(MATRIX, encoding="utf-8"):
    m = re.match(r"^### (3\.\d+) ", line)
    if m:
        section = m.group(1)
    m = re.match(r"^\| ([A-Z]{3}-\d{2}[a-z]?) \|", line)
    if m and section and section != "3.18":
        parts = [p for p in line.strip().strip("|").split("|")]
        code, cells = parts[0].strip(), parts[2:12]
        rows.append((code, dict(zip(COLS, cells))))

org, vendor = [], []
for code, cells in rows:
    for col, role in ORG_ROLES.items():
        kind, ref = cell(cells[col])
        if kind and (not code.startswith("PLT-") or code in ORG_SIDE_PLT) and code not in ("ADT-03", "ADT-04"):
            org.append((role, code, kind, ref))
    for col, role in VENDOR_ROLES.items():
        kind, ref = cell(cells[col])
        if kind and code.startswith("PLT-"):
            vendor.append((role, code))

def lit(s):
    return "None" if s is None else f'Some("{s}")'

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("//! GENERATED by docs/domain/gen_default_grants.py from PERMISSION_MATRIX.md. Do not edit by hand.\n\n")
    f.write("/// (system role code, operation code, grant kind, setting_ref): the default grants of the seven system roles (P9).\n")
    f.write("pub const SYSTEM_ROLE_GRANTS: &[(&str, &str, &str, Option<&str>)] = &[\n")
    for r in org:
        f.write(f'    ("{r[0]}", "{r[1]}", "{r[2]}", {lit(r[3])}),\n')
    f.write("];\n\n/// (vendor role, platform operation) allowed by the matrix's VA / VS / VR columns.\n")
    f.write("pub const VENDOR_ROLE_GRANTS: &[(&str, &str)] = &[\n")
    for r in vendor:
        f.write(f'    ("{r[0]}", "{r[1]}"),\n')
    f.write("];\n")
print(len(org), "organisation grants,", len(vendor), "vendor grants")
