fn reason_ok(r: &str) -> Result<(), ApiError> {
    if r.trim().is_empty() || r.chars().count() > 1000 {
        return Err(ApiError::ValidationFailed("reason is required (1-1000 characters)".into()));
    }
    Ok(())
}

